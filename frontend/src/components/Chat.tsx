export default function Chat({
  user,
  initialSessionId,
  initialTitle,
  onSessionCreated,
}: ChatProps) {
  const [messages, setMessages] = useState<Message[]>([]);
  const [input, setInput] = useState("");
  const [sending, setSending] = useState(false);
  const [error, setError] = useState("");
  const [sessionId, setSessionId] = useState<string | null>(initialSessionId);
  const [chatTitle, setChatTitle] = useState<string | null>(initialTitle);
  const [loadingMessages, setLoadingMessages] = useState(false);
  const [effort, setEffort] = useState<Effort>("flash");
  const [traceOpen, setTraceOpen] = useState(false);
  const messagesEndRef = useRef<HTMLDivElement>(null);
  const inputRef = useRef<HTMLInputElement>(null);

  // WebSocket observability — one persistent connection per session
  const {
    runs,
    snapshotRuns,
    resetRuns,
    startQuery,
    waitForConnection,
    streamingText,
    llmActive,
    connectionStatus,
    retryCount,
  } = useObservability(sessionId);

  const clearTrace = useCallback(() => {
    resetRuns();
    setTraceOpen(false);
  }, [resetRuns]);

  const scrollToBottom = useCallback(() => {
    messagesEndRef.current?.scrollIntoView({ behavior: "smooth" });
  }, []);

  useEffect(() => {
    scrollToBottom();
  }, [messages, scrollToBottom]);

  // Sync props into state during render (React-recommended pattern)
  const [prevProps, setPrevProps] = useState({ initialSessionId, initialTitle });
  if (
    prevProps.initialSessionId !== initialSessionId ||
    prevProps.initialTitle !== initialTitle
  ) {
    setPrevProps({ initialSessionId, initialTitle });
    setSessionId(initialSessionId);
    setChatTitle(initialTitle);
    setError("");
    if (!initialSessionId) {
      setMessages([]);
    }
  }

  useEffect(() => {
    if (!initialSessionId) return;
    // Skip refetch if we're already viewing this session with local messages
    // (e.g. right after creating it — DB lacks in-flight messages like MCQs).
    if (initialSessionId === sessionId && messages.length > 0) return;
    let cancelled = false;

    // Defer synchronous state update out of the effect body
    queueMicrotask(() => {
      if (!cancelled) setLoadingMessages(true);
    });

    fetchSessionMessages(user.id, initialSessionId)
      .then((data) => {
        if (cancelled) return;
        setMessages(
          data.messages.map((m) => {
            const base: Message = {
              id: String(m.id),
              role: m.role as "user" | "assistant",
              content: m.content,
              timestamp: m.created_at
                ? new Date(m.created_at).getTime()
                : Date.now(),
            };
            // Parse MCQ clarification from stored "Options:" format
            if (m.role === "assistant" && m.content.includes("Options:")) {
              const parts = m.content.split("Options:");
              let question = (parts[0] ?? "").trim();
              const optionsStr = (parts[1] ?? "").trim();
              // Detect [multi] prefix stored by backend
              let multiSelect = false;
              if (question.startsWith("[multi]")) {
                multiSelect = true;
                question = question.slice(7).trim();
              }
              const options = optionsStr
                .split("|")
                .map((o) => o.trim())
                .filter(Boolean);
              if (question && options.length > 0) {
                base.clarification = {
                  question,
                  options,
                  allow_custom: true,
                  multi_select: multiSelect,
                };
                base.content = question;
              }
            }
            return base;
          }),
        );
      })
      .catch((err) => {
        if (!cancelled) {
          setError(err instanceof Error ? err.message : "Failed to load session");
        }
      })
      .finally(() => {
        if (!cancelled) setLoadingMessages(false);
      });

    return () => {
      cancelled = true;
    };
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [initialSessionId, user.id]);

  const sendToBackend = useCallback(
    async (text: string) => {
      setSending(true);
      setError("");
      setTraceOpen(true); // surface the trace immediately on send

      // Pre-generate session ID so the WebSocket can connect before the API call
      let sid = sessionId;
      if (!sid) {
        sid = createClientId();
        setSessionId(sid);
      }

      // Reset trace for this new query + ensure WS is connected
      startQuery(sid);

      // BLOCK the POST until the WebSocket is OPEN. The backend buffers
      // events too, but awaiting here guarantees the trace starts at t=0
      // instead of racing the HTTP round-trip.
      await waitForConnection(sid);

      try {
        const response = await sendChatMessage(
          user.id,
          text,
          sid,
          effort,
        );

        // Snapshot agent trace runs so they stick to this message
        const traceRuns = snapshotRuns();

        if (response.is_new_session || !sessionId) {
          // Use the backend's session_id if it differs (should match our pre-generated one)
          const finalSid = response.session_id || sid;
          if (finalSid !== sessionId) {
            setSessionId(finalSid);
          }
          const title = response.title ?? "Untitled Chat";
          setChatTitle(title);
          onSessionCreated(finalSid, title);
        }

        if (response.type === "clarification_request" && response.clarification) {
          const mcqMsg: Message = {
            id: createClientId(),
            role: "assistant",
            content: "",
            timestamp: Date.now(),
            clarification: response.clarification,
            traceRuns: traceRuns.length > 0 ? traceRuns : undefined,
          };
          setMessages((prev) => [...prev, mcqMsg]);
        } else if (response.type === "image_generated" && response.image_data_url) {
          const imageMsg: Message = {
            id: createClientId(),
            role: "assistant",
            content: response.message ?? "Here is the generated graphic preview.",
            timestamp: Date.now(),
            imageDataUrl: response.image_data_url,
            traceRuns: traceRuns.length > 0 ? traceRuns : undefined,
          };
          setMessages((prev) => [...prev, imageMsg]);
        } else {
          const assistantMsg: Message = {
            id: createClientId(),
            role: "assistant",
            content: response.message ?? "",
            timestamp: Date.now(),
            traceRuns: traceRuns.length > 0 ? traceRuns : undefined,
          };
          setMessages((prev) => [...prev, assistantMsg]);
        }
      } catch (err) {
        setError(err instanceof Error ? err.message : "Failed to get response");
      } finally {
        setSending(false);
        inputRef.current?.focus();
      }
    },
    [user.id, sessionId, onSessionCreated, effort, snapshotRuns, startQuery, waitForConnection],
  );

  const handleSend = useCallback(async () => {
    const trimmed = input.trim();
    if (!trimmed || sending) return;

    const userMsg: Message = {
      id: createClientId(),
      role: "user",
      content: trimmed,
      timestamp: Date.now(),
    };

    setMessages((prev) => [...prev, userMsg]);
    setInput("");
    await sendToBackend(trimmed);
  }, [input, sending, sendToBackend]);

  const handleMcqAnswer = useCallback(
    async (messageId: string, question: string, answer: string) => {
      if (sending) return;

      // Mark this MCQ as answered (locks the buttons)
      setMessages((prev) =>
        prev.map((m) =>
          m.id === messageId && m.clarification
            ? { ...m, clarification: { ...m.clarification, answered: answer } }
            : m,
        ),
      );

      const userMsg: Message = {
        id: createClientId(),
        role: "user",
        content: answer,
        timestamp: Date.now(),
      };
      setMessages((prev) => [...prev, userMsg]);

      // Send only the answer — the conversation history already contains the question.
      // A verbose wrapper like "Answering your question..." pollutes the LLM context.
      await sendToBackend(answer);
    },
    [sending, sendToBackend],
  );

  const handleKeyDown = (e: React.KeyboardEvent) => {
    if (e.key === "Enter" && !e.shiftKey) {
      e.preventDefault();
      handleSend();
    }
  };

  const formatTime = (ts: number) =>
    new Date(ts).toLocaleTimeString("en-US", {
      hour: "2-digit",
      minute: "2-digit",
    });

  const isEmpty = messages.length === 0 && !loadingMessages;

  return (
    <div className="flex flex-col h-[calc(100vh-8rem)]">
      {/* Header */}
      <div className="flex items-center shrink-0 pb-3">
        {chatTitle ? (
          <div className="flex items-center gap-2.5 min-w-0">
            <div className="w-8 h-8 rounded-lg bg-[#eef2ff] flex items-center justify-center shrink-0">
              <MessageSquare className="w-4 h-4" style={{ color: ACCENT }} />
            </div>
            <span className="text-sm font-semibold text-[#0a0a0a] truncate">
              {chatTitle}
            </span>
          </div>
        ) : (
          <span className="text-sm font-medium text-[#9ca3af]">New Chat</span>
        )}
      </div>

      {loadingMessages && (
        <div className="flex items-center justify-center py-4">
          <Loader2 className="w-5 h-5 animate-spin" style={{ color: ACCENT }} />
        </div>
      )}

      {/* Messages */}
      <div className="flex-1 overflow-y-auto px-1 pb-4">
        {/* Empty state */}
        {isEmpty && (
          <motion.div initial={{ opacity: 0, scale: 0.95 }} animate={{ opacity: 1, scale: 1 }} transition={{ duration: 0.4, ease: "easeOut" }} className="h-full flex flex-col items-center justify-center text-center py-10 px-4">
            <div className="w-14 h-14 rounded-2xl flex items-center justify-center mb-6 shadow-lg shadow-[#4f46e5]/20"
              style={{ background: `linear-gradient(135deg, ${ACCENT}, #818cf8)` }}>
              <Sparkles className="w-6 h-6 text-white" />
            </div>
            <h3 className="text-xl font-bold text-[#0a0a0a] tracking-tight">
              Your AI co-founder is ready
            </h3>
            <p className="mt-2 text-[15px] text-[#6b7280] max-w-md leading-relaxed">
              I delegate to a team of specialist agents — research, writing, design,
              data analysis, and marketing. Tell me what you need shipped.
            </p>

            {/* Quick-start suggestions */}
            <div className="mt-8 grid grid-cols-1 sm:grid-cols-2 gap-3 w-full max-w-md">
              {[
                { label: "Write a marketing email", desc: "Campaigns, launches, newsletters" },
                { label: "Create an Instagram post", desc: "Captions, visuals, brand copy" },
                { label: "Analyze my sales data", desc: "EDA, charts, executive summary" },
                { label: "Research my competitors", desc: "Market landscape, positioning" },
              ].map((chip, idx) => (
                <motion.button
                  initial={{ opacity: 0, y: 10 }}
                  animate={{ opacity: 1, y: 0 }}
                  transition={{ delay: idx * 0.1 + 0.2 }}
                  key={chip.label}
                  type="button"
                  onClick={() => {
                    setInput(chip.label);
                    inputRef.current?.focus();
                  }}
                  className="group flex flex-col items-start gap-1 rounded-xl border border-[#e5e7eb] bg-white px-4 py-3.5 text-left transition-all duration-300 hover:border-[#4f46e5]/40 hover:shadow-[0_8px_24px_-8px_rgba(79,70,229,0.15)] hover:-translate-y-0.5"
                >
                  <span className="text-[13px] font-semibold text-[#374151] group-hover:text-[#4f46e5] transition-colors">
                    {chip.label}
                  </span>
                  <span className="text-[11px] text-[#9ca3af] leading-tight">
                    {chip.desc}
                  </span>
                </motion.button>
              ))}
            </div>
          </motion.div>
        )}

        <div className="space-y-6">
          <AnimatePresence initial={false}>
            {messages.map((msg) => (
              <motion.div
                key={msg.id}
                initial={{ opacity: 0, y: 8 }}
                animate={{ opacity: 1, y: 0 }}
                transition={{ duration: 0.22 }}
                className={`flex gap-3 ${msg.role === "user" ? "justify-end" : "justify-start"}`}
              >
                {msg.role === "assistant" && (
                  <div
                    className="w-8 h-8 rounded-lg flex items-center justify-center shrink-0 mt-0.5"
                    style={{ background: ACCENT }}
                  >
                    <Sparkles className="w-4 h-4 text-white" />
                  </div>
                )}

                <div
                  className={`min-w-0 ${
                    msg.role === "user"
                      ? "max-w-[75%] bg-[#0a0a0a] text-white rounded-[20px] rounded-tr-[4px] px-5 py-3 shadow-md shadow-black/5"
                      : "max-w-[85%] py-1.5"
                  }`}
                >
                  {msg.role === "assistant" && msg.clarification ? (
                    <McqCard
                      clarification={msg.clarification}
                      disabled={sending}
                      onAnswer={(answer) =>
                        handleMcqAnswer(
                          msg.id,
                          msg.clarification!.question,
                          answer,
                        )
                      }
                    />
                  ) : msg.role === "assistant" && msg.imageDataUrl ? (
                    <div className="space-y-3">
                      <MarkdownMessage content={msg.content} />
                      <GeneratedImage imageDataUrl={msg.imageDataUrl} />
                    </div>
                  ) : msg.role === "assistant" ? (
                    <AssistantMessage content={msg.content} />
                  ) : (
                    <p className="text-sm leading-relaxed whitespace-pre-wrap break-words">
                      {msg.content}
                    </p>
                  )}
                  <span
                    className={`text-[10px] mt-1.5 block font-medium ${
                      msg.role === "user" ? "text-white/50" : "text-[#9ca3af]"
                    }`}
                  >
                    {formatTime(msg.timestamp)}
                  </span>
                </div>

                {msg.role === "user" && (
                  <div className="w-8 h-8 rounded-lg bg-[#e5e7eb] flex items-center justify-center shrink-0 mt-0.5">
                    <User className="w-4 h-4 text-[#6b7280]" />
                  </div>
                )}
              </motion.div>
            ))}
          </AnimatePresence>

          {/* Typing indicator */}
          <AnimatePresence>
            {sending && (
              <motion.div
                initial={{ opacity: 0, y: 8 }}
                animate={{ opacity: 1, y: 0 }}
                exit={{ opacity: 0 }}
                className="flex gap-3"
              >
                <div
                  className="w-8 h-8 rounded-lg flex items-center justify-center shrink-0"
                  style={{ background: ACCENT }}
                >
                  <Sparkles className="w-4 h-4 text-white" />
                </div>
                <div className="flex items-center gap-1.5">
                  {[0, 150, 300].map((delay) => (
                    <span
                      key={delay}
                      className="w-1.5 h-1.5 rounded-full bg-[#4f46e5] animate-bounce"
                      style={{ animationDelay: `${delay}ms` }}
                    />
                  ))}
                </div>
              </motion.div>
            )}
          </AnimatePresence>

          {/* Live streaming response while CEO is processing */}
          <AnimatePresence>
            {sending && llmActive && streamingText.length > 0 && (
              <motion.div
                initial={{ opacity: 0, y: 8 }}
                animate={{ opacity: 1, y: 0 }}
                exit={{ opacity: 0 }}
                className="flex gap-3"
              >
                <div
                  className="w-8 h-8 rounded-lg flex items-center justify-center shrink-0 mt-0.5"
                  style={{ background: ACCENT }}
                >
                  <Sparkles className="w-4 h-4 text-white" />
                </div>
                <div className="min-w-0 max-w-[85%] py-1.5 flex-1">
                  <div className="rounded-[20px] rounded-tl-[4px] border border-[#e5e7eb] bg-white px-4 py-3 shadow-sm">
                    <p className="text-sm leading-relaxed whitespace-pre-wrap break-words text-[#374151]">
                      {streamingText}
                      <span
                        className="ml-0.5 inline-block h-3.5 w-[2px] animate-pulse rounded-full align-middle"
                        style={{ background: ACCENT }}
                      />
                    </p>
                  </div>
                </div>
              </motion.div>
            )}
          </AnimatePresence>

          {/* Error */}
          <AnimatePresence>
            {error && (
              <motion.div
                initial={{ opacity: 0, y: -8 }}
                animate={{ opacity: 1, y: 0 }}
                exit={{ opacity: 0 }}
                className="flex items-center gap-2.5 bg-red-50 border border-red-200 rounded-xl px-4 py-3"
              >
                <AlertCircle className="w-4 h-4 text-red-500 shrink-0" />
                <p className="text-[13px] font-medium text-red-600 flex-1">{error}</p>
                <button
                  onClick={() => setError("")}
                  className="text-xs font-medium text-red-500 underline shrink-0"
                >
                  Dismiss
                </button>
              </motion.div>
            )}
          </AnimatePresence>

          <div ref={messagesEndRef} />
        </div>
      </div>

      {/* Input */}
      <div className="shrink-0 pt-4 pb-2 relative z-10 before:absolute before:inset-0 before:bg-gradient-to-t before:from-[#fafafa] before:via-[#fafafa]/90 before:to-transparent before:-z-10 before:pointer-events-none">
        <div className="bg-white border border-[#e5e7eb] rounded-2xl px-4 py-2.5 flex items-center gap-3 focus-within:border-[#4f46e5] focus-within:ring-4 focus-within:ring-[#4f46e5]/10 transition-all shadow-[0_2px_12px_-4px_rgba(0,0,0,0.06)] hover:shadow-[0_4px_20px_-4px_rgba(0,0,0,0.08)]">
          {/* Effort dropdown */}
          <div className="relative shrink-0">
            <select
              value={effort}
              onChange={(e) => setEffort(e.target.value as Effort)}
              disabled={sending}
              className="appearance-none bg-[#f9fafb] border border-[#e5e7eb] rounded-xl pl-3 pr-8 py-2 text-xs font-semibold text-[#374151] cursor-pointer outline-none focus:border-[#4f46e5] hover:border-[#4f46e5]/50 transition-colors disabled:opacity-50 disabled:cursor-not-allowed"
            >
              <option value="flash">⚡ Flash</option>
              <option value="mid">⚖️ Mid</option>
              <option value="max">🎯 Max</option>
            </select>
            <ChevronDown className="absolute right-2 top-1/2 -translate-y-1/2 w-3 h-3 text-[#9ca3af] pointer-events-none" />
          </div>
          <input
            ref={inputRef}
            type="text"
            value={input}
            onChange={(e) => setInput(e.target.value)}
            onKeyDown={handleKeyDown}
            placeholder="Message your CEO agent…"
            disabled={sending}
            className="flex-1 bg-transparent text-[15px] text-[#0a0a0a] placeholder-[#9ca3af] outline-none py-1.5 disabled:opacity-50"
            autoFocus
          />
          {/* Agent trace dropdown — sits beside the chat bar */}
          <AgentTracePanel
            runs={runs}
            streamingText={streamingText}
            llmActive={llmActive}
            isStreaming={sending}
            connectionStatus={connectionStatus}
            retryCount={retryCount}
            open={traceOpen}
            onToggle={() => setTraceOpen((v) => !v)}
            onClear={clearTrace}
          />
          <button
            onClick={handleSend}
            disabled={!input.trim() || sending}
            className="w-10 h-10 rounded-xl flex items-center justify-center shrink-0 transition-all duration-300 disabled:cursor-not-allowed disabled:opacity-60"
            style={{
              background: input.trim() && !sending ? ACCENT : "#f3f4f6",
              color: input.trim() && !sending ? "#fff" : "#9ca3af",
              boxShadow: input.trim() && !sending ? "0 4px 12px -4px rgba(79, 70, 229, 0.4)" : "none",
            }}
          >
            {sending ? (
              <Loader2 className="w-4 h-4 animate-spin" />
            ) : (
              <Send className="w-4 h-4" />
            )}
          </button>
        </div>
        <p className="text-[11px] text-[#9ca3af] text-center mt-3">
          {effort === "flash"
            ? "Flash — instant responses, no reflections. Best for quick tasks."
            : effort === "mid"
              ? "Mid — balanced speed & quality with light review."
              : "Max — full agent pipeline with reflections. Highest quality."}
        </p>
      </div>
    </div>
  );
}
